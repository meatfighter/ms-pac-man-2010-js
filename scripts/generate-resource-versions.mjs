import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(rootDir, "pwa", "src", "app", "resourceManifest.ts");
const publicDir = join(rootDir, "pwa", "public");
const outputPath = join(rootDir, "pwa", "src", "app", "ResourceVersions.ts");
const checkOnly = process.argv.includes("--check");

const manifest = readFileSync(manifestPath, "utf8");
const arrayMatch = /export const RESOURCE_REFS = \[([\s\S]*?)\] as const;/.exec(manifest);
if (arrayMatch === null) {
    throw new Error("Unable to locate RESOURCE_REFS in resourceManifest.ts.");
}
const refs = Array.from(arrayMatch[1].matchAll(/"([^"]+)"/g), (match) => match[1]);
if (refs.length === 0 || new Set(refs).size !== refs.length) {
    throw new Error("RESOURCE_REFS must be a non-empty unique list.");
}

const versions = Object.fromEntries(
    refs.map((ref) => {
        const bytes = readFileSync(join(publicDir, ...ref.split("/")));
        return [ref, createHash("sha256").update(bytes).digest("hex").slice(0, 16)];
    })
);

const generated = `// Generated by scripts/generate-resource-versions.mjs. Do not edit by hand.\nexport const RESOURCE_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 4)};\n\nexport function getResourceVersion(ref: string): string | null {\n    return RESOURCE_VERSIONS[ref] ?? null;\n}\n`;

if (checkOnly) {
    const existing = readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n");
    if (existing !== generated) {
        throw new Error("ResourceVersions.ts is stale. Run npm run generate:resource-versions.");
    }
} else {
    writeFileSync(outputPath, generated);
}
